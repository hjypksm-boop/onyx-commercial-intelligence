"""The ONLY module that knows about SQL dialect differences.

SQL files use small macros that are rendered here for SQLite or PostgreSQL:

    {{PK}}                 auto-increment integer primary key column definition
    {{DAYS(a, b)}}         whole days from date b to date a  (a - b)
    {{ADD_DAYS(d, n)}}     ISO date string d plus n days     (returns 'YYYY-MM-DD')
    {{MONTH_ADD(d, n)}}    'YYYY-MM' month key of date d shifted by n months
    {{AS_OF}}              the demo clock (app_config.as_of_date) — or :as_of when rendered with param_as_of
    {{DROP_VIEW(name)}}    drop a view if it exists

All dates are stored as ISO-8601 TEXT so plain comparisons work in both engines.
"""
from __future__ import annotations

import re

AS_OF_SUBQUERY = "(SELECT value FROM app_config WHERE key = 'as_of_date')"

_MACRO_START = re.compile(r"\{\{([A-Z_]+)(\()?")


def _split_args(s: str) -> list[str]:
    args, depth, cur = [], 0, []
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            args.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    args.append("".join(cur).strip())
    return args


def _expand(name: str, args: list[str], dialect: str, param_as_of: bool) -> str:
    pg = dialect.startswith("postgres")
    if name == "PK":
        return "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if pg else "INTEGER PRIMARY KEY AUTOINCREMENT"
    if name == "AS_OF":
        return ":as_of" if param_as_of else AS_OF_SUBQUERY
    if name == "DAYS":
        a, b = args
        if pg:
            return f"(CAST({a} AS DATE) - CAST({b} AS DATE))"
        return f"CAST(ROUND(julianday({a}) - julianday({b})) AS INTEGER)"
    if name == "ADD_DAYS":
        d, n = args
        if pg:
            return f"to_char(CAST({d} AS DATE) + CAST({n} AS INTEGER), 'YYYY-MM-DD')"
        return f"date({d}, ({n}) || ' days')"
    if name == "MONTH_ADD":
        d, n = args
        if pg:
            return (f"to_char(date_trunc('month', CAST({d} AS DATE)) + make_interval(months => CAST({n} AS INTEGER)), "
                    f"'YYYY-MM')")
        return f"strftime('%Y-%m', {d}, 'start of month', ({n}) || ' months')"
    if name == "DROP_VIEW":
        (v,) = args
        return f"DROP VIEW IF EXISTS {v} CASCADE" if pg else f"DROP VIEW IF EXISTS {v}"
    raise ValueError(f"Unknown SQL macro {name}")


def render(sql: str, dialect: str = "sqlite", param_as_of: bool = False) -> str:
    """Expand all macros (supports nesting) for the given dialect name."""
    out = sql
    while True:
        m = _MACRO_START.search(out)
        if not m:
            return out
        name, has_args = m.group(1), m.group(2)
        if not has_args:
            end = out.index("}}", m.end())
            out = out[: m.start()] + _expand(name, [], dialect, param_as_of) + out[end + 2:]
            continue
        # find matching ')' followed by '}}'
        depth, i = 1, m.end()
        while depth:
            if out[i] == "(":
                depth += 1
            elif out[i] == ")":
                depth -= 1
            i += 1
        inner = out[m.end(): i - 1]
        if out[i: i + 2] != "}}":
            raise ValueError(f"Malformed macro near: {out[m.start(): i + 10]}")
        # render nested macros inside args first
        args = [render(a, dialect, param_as_of) for a in _split_args(inner)]
        out = out[: m.start()] + _expand(name, args, dialect, param_as_of) + out[i + 2:]


def split_statements(sql: str) -> list[str]:
    """Split a SQL script on ';' at line ends. SQL files must not contain ';' inside string literals."""
    lines = [ln for ln in sql.splitlines() if not ln.strip().startswith("--")]
    parts = "\n".join(lines).split(";")
    return [p.strip() for p in parts if p.strip()]
